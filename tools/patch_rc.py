#!/usr/bin/env python3
"""Small, idempotent edits to the Godot source that the release build needs.

Used by ``tools/build_windows_exe.sh``. Two jobs:

  patch_rc.py <godot_res.rc>
      Write the Windows resource script that is compiled into the export
      template: the game's icon, its name and its version. Without this the exe
      would carry the engine's own naming; with it, the single-file build needs
      no rcedit pass at export time (rcedit is a Windows-only tool).

  patch_rc.py --win-libs <platform/windows/detect.py>
      The Windows link line lists some libraries with their canonical Windows
      capitalisation (IPHLPAPI, Shlwapi, Ws2_32, ...). zig's linker resolves
      ``-l`` names case-sensitively, so lower-case them; mingw ignores case, so
      this changes nothing for a normal mingw build.

Both forms are idempotent and both refuse to run on anything that is not the file
they expect, so a typo (``patch_rc.py --help``, a stray flag) cannot write a
resource script on top of a source file or create a file named after the flag.

The version is not duplicated here: it is read from ``scripts/version.gd``, the
canonical source ``tools/sync_version.py`` already keeps ``project.godot`` and
``export_presets.cfg`` in step with, so a version bump cannot leave the exe's
Windows metadata behind.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PRODUCT = "The Violence"
ROOT = Path(__file__).resolve().parents[1]
VERSION_GD = ROOT / "scripts" / "version.gd"


def version() -> str:
    """The Windows four-part version, from scripts/version.gd (the canonical source).

    There is no fallback constant: a build that cannot read the version must stop,
    not stamp the exe with a number nobody bumped (the old hardcoded fallback was
    the one place a version bump could leave behind).
    """
    try:
        source = VERSION_GD.read_text(encoding="utf-8")
    except OSError as exc:
        raise SystemExit(f"patch_rc: cannot read {VERSION_GD}: {exc}") from exc
    match = re.search(r'^const\s+VALUE\s*:=\s*"([^"]+)"', source, re.MULTILINE)
    if not match:
        raise SystemExit(f"patch_rc: {VERSION_GD} has no const VALUE")
    parts = [p for p in match.group(1).split(".") if p != ""]
    while len(parts) < 4:
        parts.append("0")
    return ".".join(parts[:4])


VERSION = version()


def ver_commas(v: str) -> str:
    """1.2.1.0 -> 1,2,1,0. Every part kept: rstrip(',0') used to eat a real 0
    (a 1.2.10.0 build became 1,2,1,0) and the fallback hardcoded one version."""
    parts = (v.split(".") + ["0", "0", "0", "0"])[:4]
    return ",".join(str(int(p)) if p.isdigit() else "0" for p in parts)

RC_TEMPLATE = """\
// Generated by tools/patch_rc.py for The Violence release builds.
#include "core/version.h"

#ifndef RT_MANIFEST
#define RT_MANIFEST 24
#endif

GODOT_ICON ICON platform/windows/godot.ico
1 RT_MANIFEST "godot.manifest"

1 VERSIONINFO
FILEVERSION     {ver_commas}
PRODUCTVERSION  {ver_commas}
FILEOS          4
FILETYPE        1
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName",            ""
            VALUE "FileDescription",        "{product}"
            VALUE "FileVersion",            "{version}"
            VALUE "ProductName",            "{product}"
            VALUE "ProductVersion",         "{version}"
            VALUE "LegalCopyright",         ""
            VALUE "OriginalFilename",       "TheViolence.exe"
            VALUE "Info",                   ""
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"""

WINDOWS_LIBS = ["IPHLPAPI", "Shlwapi", "Ws2_32", "Crypt32", "Avrt"]


def patch_rc(path: str) -> int:
    text = RC_TEMPLATE.format(
        product=PRODUCT,
        version=VERSION,
        ver_commas=ver_commas(VERSION),
    )
    current = ""
    try:
        current = open(path, encoding="utf-8").read()
    except OSError:
        pass
    if current and "GODOT_ICON" not in current:
        print("rc: %s does not look like godot_res.rc; refusing to overwrite it" % path, file=sys.stderr)
        return 2
    if current == text:
        print("rc: already branded for %s %s" % (PRODUCT, VERSION))
        return 0
    open(path, "w", encoding="utf-8").write(text)
    print("rc: wrote %s %s resources" % (PRODUCT, VERSION))
    return 0


def patch_win_libs(path: str) -> int:
    try:
        src = open(path, encoding="utf-8").read()
    except OSError as exc:
        print("detect.py: cannot read %s: %s" % (path, exc), file=sys.stderr)
        return 2
    if "def get_opts" not in src:
        print("detect.py: %s does not look like platform/windows/detect.py" % path, file=sys.stderr)
        return 2
    out = src
    for lib in WINDOWS_LIBS:
        out = out.replace('        "%s",' % lib, '        "%s",' % lib.lower())
    if out == src:
        print("detect.py: library names already lower-case")
        return 0
    open(path, "w", encoding="utf-8").write(out)
    print("detect.py: lower-cased %s" % ", ".join(WINDOWS_LIBS))
    return 0


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 2 if not argv else 0
    if argv[0] == "--win-libs":
        if len(argv) < 2:
            print("patch_rc: --win-libs needs a path to platform/windows/detect.py", file=sys.stderr)
            return 2
        return patch_win_libs(argv[1])
    if argv[0].startswith("-"):
        print("patch_rc: unknown option %r (see --help)" % argv[0], file=sys.stderr)
        return 2
    if len(argv) > 1:
        print("patch_rc: unexpected extra arguments %r" % (argv[1:],), file=sys.stderr)
        return 2
    return patch_rc(argv[0])


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
